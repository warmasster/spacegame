# accented capitals: the plain letter one row down under an accent (drawn in the cap row)
for acc, base in {"Á": "A", "É": "E", "Í": "I", "Ó": "O", "Ú": "U"}.items():
    G[acc] = ["   # "] + G[base][1:]
G["Ñ"] = [" ## #"] + G["N"][1:]


def draw(px, x, y, text, color, scale=1):
    """Draw `text` with its top-left at (x, y) on a `Pix`-like (with .px(x, y, c)), `scale` pixels per dot."""
    cx = x
    for ch in text.upper():
        g = G.get(ch, G["?"])
        for r, row in enumerate(g):
            for c, dot in enumerate(row):
                if dot == "#":
                    for sy in range(scale):
                        for sx in range(scale):
                            px.px(cx + c * scale + sx, y + r * scale + sy, color)
        cx += 6 * scale
    return cx - x


def width(text, scale=1):
    return (len(text) * 6 - 1) * scale


def centered(px, cx, y, text, color, scale=1):
    draw(px, cx - width(text, scale) // 2, y, text, color, scale)
